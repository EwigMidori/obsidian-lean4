/** Owns UI text only. Lean source, proof goals, diagnostics and process logs stay verbatim. */
export class LeanI18n {
  static locale(): LeanLocale {
    const language = (typeof getLanguage === "function" ? getLanguage() : "en")
      .trim().replaceAll("_", "-").toLowerCase();
    return language === "zh" || language === "zh-cn" || language === "zh-hans" || language.startsWith("zh-hans-")
      ? "zh-CN" : "en";
  }

  static catalog(locale: LeanLocale): Readonly<Record<LeanTextKey, string>> {
    return locale === "zh-CN" ? simplifiedChinese : english;
  }

  static text(key: LeanTextKey, parameters: Readonly<Record<string, string | number>> = {}): string {
    const template = this.catalog(this.locale())[key] ?? english[key];
    return template.replace(/\{([a-zA-Z][a-zA-Z0-9]*)\}/gu, (token, name: string) =>
      Object.prototype.hasOwnProperty.call(parameters, name) ? String(parameters[name]) : token);
  }
}
